"""Generates Plugins/Enginewright/Scripts/ew_font.py: the bitmap font used by `ewtool.py compose` labels.

Developer tool only (needs Pillow); the generated file is committed, so users never run this.
The glyphs are rasterized from Droid Sans Mono (Apache License 2.0), which ships with Unreal Engine in
Engine/Content/Slate/Fonts/DroidSansMono.ttf.

Usage:
    python tools/make_font.py --engine "C:/Program Files/Epic Games/UE_5.8" [--size 15]
"""
import argparse, base64, pathlib, zlib

from PIL import Image, ImageDraw, ImageFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "Plugins" / "Enginewright" / "Scripts" / "ew_font.py"
CHARS = (
    [chr(c) for c in range(32, 127)]
    + [chr(c) for c in range(160, 384)]           # Latin-1 Supplement + Latin Extended-A (Turkish, Polish, Czech, ...)
    + list("\u2013\u2014\u2018\u2019\u201c\u201d\u2022\u2026\u2190\u2192\u2191\u2193\u20ac\u2116")
)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--engine", required=True)
    ap.add_argument("--size", type=int, default=15)
    a = ap.parse_args()
    ttf = pathlib.Path(a.engine) / "Engine/Content/Slate/Fonts/DroidSansMono.ttf"
    font = ImageFont.truetype(str(ttf), a.size)
    ascent, descent = font.getmetrics()
    cw = round(font.getlength("M"))
    top_pad = 3  # room for accents above capitals
    ch = ascent + descent + top_pad
    chars = [c for c in CHARS if font.getmask(c).getbbox() or c == " " or c == "\u00a0"]
    raw = bytearray()
    for c in chars:
        img = Image.new("L", (cw, ch), 0)
        ImageDraw.Draw(img).text((0, top_pad), c, font=font, fill=255)
        raw += img.tobytes()
    data = base64.b64encode(zlib.compress(bytes(raw), 9)).decode()
    lines = [data[i:i + 100] for i in range(0, len(data), 100)]
    OUT.write_text(
        '"""Bitmap font for ewtool.py compose labels. Generated by tools/make_font.py, do not edit.\n\n'
        "Glyphs rasterized from Droid Sans Mono, Copyright (C) 2008 The Android Open Source Project,\n"
        'licensed under the Apache License, Version 2.0 (http://www.apache.org/licenses/LICENSE-2.0).\n"""\n'
        f"CELL_W = {cw}\nCELL_H = {ch}\nCHARS = {''.join(chars)!r}\n"
        "DATA = (\n" + "".join(f'    "{l}"\n' for l in lines) + ")\n",
        encoding="utf-8", newline="\n")
    print(f"{OUT}: {len(chars)} glyphs, cell {cw}x{ch}, {len(data)} base64 chars")


if __name__ == "__main__":
    main()
