"""Generates Plugins/Enginewright/Source/Enginewright/Private/EWFontData.inl: the bitmap font that the
`image_compose` tool uses for its labels.

Developer tool only (needs Pillow); the generated file is committed, so users never run this.
The glyphs are rasterized from Droid Sans Mono (Apache License 2.0), which ships with Unreal Engine in
Engine/Content/Slate/Fonts/DroidSansMono.ttf.

Usage:
    python tools/make_font.py --engine "C:/Program Files/Epic Games/UE_5.8" [--size 15]
"""
import argparse, pathlib, zlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "Plugins" / "Enginewright" / "Source" / "Enginewright" / "Private" / "EWFontData.inl"
CHARS = (
    [chr(c) for c in range(32, 127)]
    + [chr(c) for c in range(160, 384)]           # Latin-1 Supplement + Latin Extended-A (Turkish, Polish, Czech, ...)
    + list("\u2013\u2014\u2018\u2019\u201c\u201d\u2022\u2026\u2190\u2192\u2191\u2193\u20ac\u2116")
)


def rasterize(engine, size):
    from PIL import Image, ImageDraw, ImageFont
    ttf = pathlib.Path(engine) / "Engine/Content/Slate/Fonts/DroidSansMono.ttf"
    font = ImageFont.truetype(str(ttf), size)
    ascent, descent = font.getmetrics()
    cw = round(font.getlength("M"))
    top_pad = 3  # room for accents above capitals
    ch = ascent + descent + top_pad
    chars = [c for c in CHARS if font.getmask(c).getbbox() or c == " " or c == "\u00a0"]
    raw = bytearray()
    for c in chars:
        img = Image.new("L", (cw, ch), 0)
        ImageDraw.Draw(img).text((0, top_pad), c, font=font, fill=255)
        raw += img.tobytes()
    return cw, ch, chars, bytes(raw)


def write_inl(cw, ch, chars, raw, out=OUT):
    assert len(raw) == cw * ch * len(chars)
    z = zlib.compress(raw, 9)

    def rows(vals, per):
        vals = list(vals)
        return "".join("\t" + ",".join(str(v) for v in vals[i:i + per]) + ",\n" for i in range(0, len(vals), per))
    out.write_text(
        "// Bitmap font for image_compose labels. Generated by tools/make_font.py, do not edit.\n"
        "// Glyphs rasterized from Droid Sans Mono, Copyright (C) 2008 The Android Open Source Project,\n"
        "// licensed under the Apache License, Version 2.0 (http://www.apache.org/licenses/LICENSE-2.0).\n"
        "// Layout: zlib stream of NumGlyphs cells, CellW x CellH bytes each (alpha 0-255, row by row).\n"
        f"static constexpr int32 GEWFontCellW = {cw};\n"
        f"static constexpr int32 GEWFontCellH = {ch};\n"
        f"static constexpr int32 GEWFontRawSize = {len(raw)};\n"
        f"static const uint16 GEWFontChars[{len(chars)}] = {{\n" + rows((ord(c) for c in chars), 24) + "};\n"
        f"static const uint8 GEWFontZ[{len(z)}] = {{\n" + rows(z, 40) + "};\n",
        encoding="utf-8", newline="\n")
    print(f"{out}: {len(chars)} glyphs, cell {cw}x{ch}, {len(z)} compressed bytes")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--engine", required=True)
    ap.add_argument("--size", type=int, default=15)
    a = ap.parse_args()
    write_inl(*rasterize(a.engine, a.size))


if __name__ == "__main__":
    main()
